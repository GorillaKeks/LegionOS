const messages: Record<Language, Messages> = { en, de, nl };

export function st(language: Language, key: string, values: Record<string, string | number> = {}): string {
  let value = messages[language]?.[key] ?? en[key] ?? key;
  for (const [name, replacement] of Object.entries(values)) value = value.split(`{${name}}`).join(String(replacement));
  return value;
}

export function backendErrorMessage(language: Language, error: { code: string; retryAfterSecs?: number }): string {
  if (error.code === "rate_limited") {
    return error.retryAfterSecs ? st(language, "error.rate_limited", { seconds: error.retryAfterSecs }) : st(language, "error.rate_limited_unknown");
  }
  const key = `error.${error.code}`;
  return st(language, key) === key ? st(language, "error.internal") : st(language, key);
}

export function formatTime(ms: number): string {
  const total = Math.max(0, Math.floor(ms / 1000));
  const hours = Math.floor(total / 3600);
  const minutes = Math.floor((total % 3600) / 60);
  const seconds = String(total % 60).padStart(2, "0");
  return hours > 0 ? `${hours}:${String(minutes).padStart(2, "0")}:${seconds}` : `${minutes}:${seconds}`;
}

